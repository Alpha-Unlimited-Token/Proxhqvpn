// Inspect a QUIC packet payload (simulates SNI extraction from QUIC Initial)
router.post("/quic/inspect", async (req, res) => {
  const body = z.object({
    srcIp:    z.string().min(1),
    dstIp:    z.string().min(1),
    srcPort:  z.number().int().optional(),
    dstPort:  z.number().int().default(443),
    hexPayload: z.string().optional(),      // raw UDP payload in hex
    sni:      z.string().optional(),        // if already extracted by DPI
  }).parse(req.body);

  // Simulate QUIC Initial SNI extraction
  let extractedSni = body.sni ?? null;
  let quicVersion = "1";
  let echDetected = false;
  let connectionId = Math.random().toString(16).slice(2, 18).toUpperCase();

  if (body.hexPayload) {
    const buf = Buffer.from(body.hexPayload, "hex");
    // QUIC Initial: first byte bit7=1 (long header), bits 4-5 = 00 (Initial)
    if (buf.length > 0 && (buf[0] & 0xc0) === 0xc0) {
      quicVersion = buf.slice(1, 5).toString("hex") === "00000001" ? "1" : "2";
    }
    // Check for ECH extension (0xfe0d in ClientHello extensions)
    if (body.hexPayload.includes("fe0d")) echDetected = true;
    // Simple SNI search in hex — look for common TLD patterns
    const decoded = buf.toString("utf8", 0, Math.min(buf.length, 512));
    const sniMatch = decoded.match(/(?<=[^\x20-\x7e]|^)([a-z0-9-]{1,63}\.(?:com|net|org|io|dev|app|cloud|co|uk|de|ru|cn|ir))/);
    if (sniMatch) extractedSni = sniMatch[1];
  }

  const action = extractedSni?.match(/malware|evil|c2|bot|ransom/i) ? "block" : "log";

  const [event] = await db.insert(quicEventsTable).values({
    srcIp: body.srcIp, dstIp: body.dstIp,
    srcPort: body.srcPort, dstPort: body.dstPort,
    sni: extractedSni, connectionId, quicVersion, echDetected, action,
  }).returning();

  res.json({ event, extractedSni, quicVersion, echDetected, connectionId, action,
    analysis: {
      sniExposed: !echDetected && !!extractedSni,
      threat: action === "block" ? "Malicious SNI detected" : null,
      note: echDetected ? "ECH active — SNI encrypted, only outer public_name visible" : "SNI visible in QUIC Initial packet TLS ClientHello",
    }
  });
});

