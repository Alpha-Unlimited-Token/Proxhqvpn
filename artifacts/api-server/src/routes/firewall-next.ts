router.post("/rpki/validate", async (req, res) => {
  const body = z.object({
    prefix: z.string().min(1),   // e.g. "1.1.1.0/24"
    asn:    z.number().int().min(1).optional(),  // origin ASN to validate
  }).parse(req.body);

  // Check cache first (24h TTL)
  const cutoff = new Date(Date.now() - 86400000);
  const [cached] = await db.select().from(rpkiChecksTable)
    .where(and(eq(rpkiChecksTable.prefix, body.prefix), gte(rpkiChecksTable.checkedAt, cutoff)));
  if (cached) return res.json({ cached: true, ...cached });

  // Query Cloudflare RPKI API (real call)
  let status: "valid"|"invalid"|"not_found"|"error" = "not_found";
  let validatedOriginAsn: number | null = null;
  let maxLength: number | null = null;
  let roaCount = 0;
  let invalidReasons: string | null = null;

  try {
    const url = `https://rpki.cloudflare.com/api/v1/validity/${body.asn ?? 0}/${body.prefix}`;
    const resp = await fetch(url, { signal: AbortSignal.timeout(5000) });
    if (resp.ok) {
      const data = await resp.json() as { state?: string; reason?: string; vrps?: Array<{ asn: number; prefix: string; max_length: number }> };
      if (data.state === "valid")   status = "valid";
      else if (data.state === "invalid") { status = "invalid"; invalidReasons = data.reason ?? null; }
      else status = "not_found";
      roaCount = data.vrps?.length ?? 0;
      validatedOriginAsn = data.vrps?.[0]?.asn ?? null;
      maxLength = data.vrps?.[0]?.max_length ?? null;
    } else {
      // Fallback: try RIPE Stat
      const ripeUrl = `https://stat.ripe.net/data/rpki-validation/data.json?resource=${body.prefix}&sourceapp=proxhqvpn`;
      const ripeResp = await fetch(ripeUrl, { signal: AbortSignal.timeout(5000) });
      if (ripeResp.ok) {
        const ripeData = await ripeResp.json() as { data?: { status?: string; validating_roas?: Array<{ origin: number; prefix: string; max_length: number }> } };
        status = ripeData.data?.status === "valid" ? "valid" : ripeData.data?.status === "invalid" ? "invalid" : "not_found";
        roaCount = ripeData.data?.validating_roas?.length ?? 0;
      }
    }
  } catch {
    status = "error";
  }

  const [saved] = await db.insert(rpkiChecksTable).values({
    prefix: body.prefix, asn: body.asn, validatedOriginAsn, maxLength, status, roaCount, invalidReasons,
  }).returning();

  res.json({ ...saved, cached: false,
    interpretation: {
      valid: "✅ ROA exists and origin ASN matches — route is cryptographically verified",
      invalid: "❌ ROA exists but origin ASN or prefix length does not match — possible hijack",
      not_found: "⚠️ No ROA found — route cannot be verified (not necessarily malicious but not secured)",
      error: "⚠️ Validation failed — API unreachable",
    }[status],
    bgpHijackRisk: status === "invalid" ? "HIGH — invalid RPKI indicates unauthorized route announcement" : status === "not_found" ? "MEDIUM — route unverified" : "LOW",
  });
});

