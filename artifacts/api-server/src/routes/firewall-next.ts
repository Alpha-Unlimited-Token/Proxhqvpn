// ML heuristic classification of a flow
router.post("/eta/classify", async (req, res) => {
  const body = z.object({
    srcIp:        z.string().min(1),
    dstIp:        z.string().min(1),
    dstPort:      z.number().int().optional(),
    protocol:     z.string().default("tcp"),
    packetCount:  z.number().int().min(1),
    byteCount:    z.number().int().min(1),
    avgPacketSize:z.number().optional(),
    maxPacketSize:z.number().optional(),
    minPacketSize:z.number().optional(),
    byteEntropy:  z.number().min(0).max(8).optional(),
    iatMeanMs:    z.number().optional(),
    iatStdMs:     z.number().optional(),
    burstCount:   z.number().int().optional(),
    flowDurationMs:z.number().optional(),
  }).parse(req.body);

  const avg = body.avgPacketSize ?? (body.byteCount / body.packetCount);
  const entropy = body.byteEntropy ?? 7.2;
  const iat = body.iatMeanMs ?? 0;
  const iatStd = body.iatStdMs ?? 0;
  const port = body.dstPort ?? 443;

  // Heuristic classification engine (based on CICFlowMeter / NetML-2020 research)
  type EtaClass = "streaming"|"vpn"|"c2_beacon"|"malware"|"browsing"|"voip"|"gaming"|"p2p"|"encrypted_dns"|"unknown";
  let classification: EtaClass = "unknown";
  let confidence = 0;
  let reason = "";

  // C2 Beaconing: low packet count, very regular timing (low IAT std), small packets
  if (iatStd < 50 && iatStd > 0 && body.packetCount < 20 && avg < 200) {
    classification = "c2_beacon"; confidence = 0.89; reason = "Regular beacon interval (IAT std < 50ms), small packets";
  }
  // Malware: high entropy (encrypted), unusual ports, large data transfer
  else if (entropy > 7.5 && port > 1024 && port !== 443 && port !== 8443 && body.byteCount > 1000000) {
    classification = "malware"; confidence = 0.78; reason = "High entropy exfil on non-standard port";
  }
  // VoIP: small packets, high packet rate, low IAT
  else if (avg < 300 && iat < 20 && body.packetCount > 100) {
    classification = "voip"; confidence = 0.85; reason = "Small packets with low IAT consistent with RTP/VoIP";
  }
  // Streaming: large average packet size, sustained high throughput
  else if (avg > 1000 && body.byteCount > 5000000) {
    classification = "streaming"; confidence = 0.82; reason = "Large sustained throughput typical of video streaming";
  }
  // VPN: high entropy, mixed packet sizes, port 443 or 51820
  else if (entropy > 7.0 && (port === 443 || port === 51820 || port === 1194 || port === 4433)) {
    classification = "vpn"; confidence = 0.74; reason = "High entropy on VPN port";
  }
  // Gaming: mixed small/large, low latency, UDP
  else if (body.protocol === "udp" && avg < 500 && iat < 50) {
    classification = "gaming"; confidence = 0.71; reason = "UDP low-latency traffic matching gaming profile";
  }
  // P2P: many peers, port 6881-6889 or random high ports, high byte count
  else if ((port >= 6881 && port <= 6889) || (port > 50000 && body.byteCount > 10000000)) {
    classification = "p2p"; confidence = 0.76; reason = "Port and traffic profile matching BitTorrent/P2P";
  }
  // Encrypted DNS (DoH/DoT): port 443/853, small packets
  else if ((port === 853 || port === 443) && avg < 400 && body.packetCount < 10) {
    classification = "encrypted_dns"; confidence = 0.81; reason = "Small packet count on DoH/DoT port";
  }
  // Browsing: standard HTTP/HTTPS pattern
  else if (port === 443 || port === 80) {
    classification = "browsing"; confidence = 0.68; reason = "Standard HTTPS browsing pattern";
  }
  else {
    classification = "unknown"; confidence = 0.40; reason = "No strong heuristic match";
  }

  const [flow] = await db.insert(etaFlowsTable).values({
    srcIp: body.srcIp, dstIp: body.dstIp, dstPort: body.dstPort, protocol: body.protocol,
    packetCount: body.packetCount, byteCount: body.byteCount,
    avgPacketSize: avg, maxPacketSize: body.maxPacketSize, minPacketSize: body.minPacketSize,
    byteEntropy: entropy, iatMeanMs: iat, iatStdMs: iatStd,
    burstCount: body.burstCount, classification, confidencePct: confidence * 100,
    action: classification === "c2_beacon" || classification === "malware" ? "block" : "log",
    flowEnd: new Date(),
  }).returning();

  res.json({ flow, classification, confidence: Math.round(confidence * 100), reason,
    features: { avgPacketSize: avg, entropy, iatMean: iat, iatStd, packetCount: body.packetCount },
    threat: classification === "c2_beacon" ? "C2 beaconing detected — automated exfil or remote control" :
            classification === "malware" ? "High-entropy data exfiltration on non-standard port" : null,
  });
});

