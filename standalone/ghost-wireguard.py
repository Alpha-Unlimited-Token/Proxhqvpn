# ── Hash helpers ──────────────────────────────────────────────────────────────
def blake2s(data: bytes, key: Optional[bytes] = None, length: int = 32) -> bytes:
    if key:
        return hashlib.blake2s(data, key=key[:32], digest_size=length).digest()
    return hashlib.blake2s(data, digest_size=length).digest()

def dh(private_key: X25519PrivateKey, public_bytes: bytes) -> bytes:
    pub = X25519PublicKey.from_public_bytes(public_bytes)
    return private_key.exchange(pub)

def chacha20poly1305_encrypt(key: bytes, nonce_int: int, aad: bytes, plaintext: bytes) -> bytes:
    nonce = struct.pack("<Q", nonce_int) + b"\x00" * 4
    return ChaCha20Poly1305(key).encrypt(nonce, plaintext, aad)

# ── Parse WireGuard Handshake Initiation ─────────────────────────────────────
def parse_handshake_init(data: bytes) -> Optional[Dict]:
    if len(data) != 148:
        return None
    if data[0] != WG_TYPE_HANDSHAKE_INIT:
        return None
    return {
        "type":                  data[0],
        "reserved":              data[1:4],
        "sender_index":          struct.unpack("<I", data[4:8])[0],
        "unencrypted_ephemeral": data[8:40],
        "encrypted_static":      data[40:88],
        "encrypted_timestamp":   data[88:116],
        "mac1":                  data[116:132],
        "mac2":                  data[132:148],
    }

# ── Build a convincing Handshake Response ─────────────────────────────────────
def build_handshake_response(init: Dict) -> Tuple[bytes, Dict]:
    our_ephemeral_private = X25519PrivateKey.generate()
    our_ephemeral_public = our_ephemeral_private.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw
    )

    initiator_ephemeral = init["unencrypted_ephemeral"]
    our_sender_index = secrets.randbelow(0xFFFFFFFF)
    receiver_index = init["sender_index"]

    dh_ee = dh(our_ephemeral_private, initiator_ephemeral)

    response_key = blake2s(
        dh_ee + initiator_ephemeral + our_ephemeral_public + _ghost_public_key_bytes,
        key=None, length=32
    )
    encrypted_nothing = chacha20poly1305_encrypt(response_key, 0, b"", b"")[:16]

    mac1_key = blake2s(LABEL_MAC1 + _ghost_public_key_bytes)
    response_body = (
        bytes([WG_TYPE_HANDSHAKE_RESPONSE]) +
        b"\x00\x00\x00" +
        struct.pack("<I", our_sender_index) +
        struct.pack("<I", receiver_index) +
        our_ephemeral_public +
        encrypted_nothing
    )
    mac1 = blake2s(response_body, key=mac1_key[:32])[:16]
    mac2 = b"\x00" * 16

    response = response_body + mac1 + mac2

    session_info = {
        "our_sender_index":    our_sender_index,
        "receiver_index":      receiver_index,
        "our_ephemeral_pub":   our_ephemeral_public.hex(),
        "initiator_ephemeral": initiator_ephemeral.hex(),
        "dh_ee_hash":          hashlib.sha256(dh_ee).hexdigest()[:16],
    }

    return response, session_info

