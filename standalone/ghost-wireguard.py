# ── Rate limiting ─────────────────────────────────────────────────────────────
RATE_LIMIT_MAX = 5
RATE_LIMIT_WIN = 60
_rate_buckets: Dict[str, list] = defaultdict(list)
_rate_lock = threading.Lock()

def is_rate_limited(ip: str) -> bool:
    now = time.time()
    with _rate_lock:
        times = _rate_buckets[ip]
        _rate_buckets[ip] = [t for t in times if now - t < RATE_LIMIT_WIN]
        if len(_rate_buckets[ip]) >= RATE_LIMIT_MAX:
            return True
        _rate_buckets[ip].append(now)
        return False

